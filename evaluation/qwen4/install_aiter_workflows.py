"""Install thin AITER callers pinned to a published SGLang harness commit."""

import argparse
from pathlib import Path

from common import ROOT, SHA


def render(harness_sha):
    if not SHA.fullmatch(harness_sha):
        raise ValueError("Use a full immutable SGLang commit SHA")
    workflows = ROOT.parents[1] / ".github/workflows"
    main = (workflows / "qwen4-ci.yml").read_text()
    schedule = '  schedule:\n    - cron: "0 20 * * *"\n'
    if schedule not in main:
        raise ValueError(
            "Update the caller generator for the changed nightly configuration"
        )
    main = main.replace("name: Qwen4 MI308X CI", "name: Qwen4 AITER downstream CI", 1)
    main = main.replace(
        "branches: [qwen4_v0.5.21]", "branches: [qwen38-flash-next-dev]", 1
    )
    main = main.replace(schedule, "", 1)
    main = main.replace(
        "uses: ./.github/workflows/_qwen4-eval.yml",
        f"uses: apinge/sglang/.github/workflows/_qwen4-eval.yml@{harness_sha}",
        1,
    )
    main = main.replace(
        "harness_sha: ${{ github.sha }}", f"harness_sha: {harness_sha}", 1
    )
    comments = (workflows / "qwen4-ci-comments.yml").read_text()
    comments = comments.replace(
        "          persist-credentials: false",
        f"          repository: apinge/sglang\n          ref: {harness_sha}\n          persist-credentials: false",
        1,
    )
    header = "# Generated by SGLang evaluation/qwen4/install_aiter_workflows.py\n"
    return {
        "qwen4-downstream.yml": header + main,
        "qwen4-ci-comments.yml": header + comments,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--harness-sha", required=True)
    parser.add_argument("--aiter-dir", required=True)
    args = parser.parse_args()
    destination = Path(args.aiter_dir) / ".github/workflows"
    destination.mkdir(parents=True, exist_ok=True)
    for name, content in render(args.harness_sha).items():
        target = destination / name
        if target.exists() and not target.read_text().startswith(
            "# Generated by SGLang evaluation/qwen4/"
        ):
            raise ValueError(f"Refusing to overwrite an unrelated workflow: {target}")
        target.write_text(content)
        print(target)
